internal data class NStroke(val path: String, val width: Float)

internal fun nIcon(
    name: String,
    width: Float,
    height: Float,
    fill: List<String> = emptyList(),
    stroke: List<NStroke> = emptyList(),
): ImageVector {
    val builder = ImageVector.Builder(
        name = name,
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = width,
        viewportHeight = height,
    )
    fill.forEach { d ->
        builder.addPath(PathParser().parsePathString(d).toNodes(), fill = SolidColor(Color.Black))
    }
    stroke.forEach { s ->
        builder.addPath(
            pathData = PathParser().parsePathString(s.path).toNodes(),
            stroke = SolidColor(Color.Black),
            strokeLineWidth = s.width,
            strokeLineCap = StrokeCap.Round,
            strokeLineJoin = StrokeJoin.Round,
        )
    }
    return builder.build()
}
